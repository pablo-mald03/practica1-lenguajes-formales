    private void textLogConfigKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_textLogConfigKeyReleased
        //Detecta cada vez que se hace un cambio

        int code = evt.getKeyCode();
        if (code == KeyEvent.VK_CONTROL || code == KeyEvent.VK_SHIFT
                || code == KeyEvent.VK_ALT
                || code == KeyEvent.VK_LEFT || code == KeyEvent.VK_RIGHT || code == KeyEvent.VK_UP || code == KeyEvent.VK_DOWN
                || code == KeyEvent.VK_TAB || code == KeyEvent.VK_CAPS_LOCK) {
            return;
        }

        if (this.textLogConfig.getText().isBlank()) {
            return;
        }

        this.hayCambio = true; 
    }//GEN-LAST:event_textLogConfigKeyReleased

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        //Boton manual que permite analizar el texto
        if (this.textLogConfig.getText().isBlank()) {
            JOptionPane.showMessageDialog(this, "NO PUEDES BORRAR LA CONFIGURACION PREDETERMINADA\nCIERRE LA VENTANA", "CONFIG EN BLANCO", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        try {
            if(this.gestionLecturas.getDatosConfig().comprobarEntradas(this.textLogConfig.getText())){
                System.out.println("todo ok");
            }

        } catch (ErrorEncontradoException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Formato incorrecto", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void formWindowClosing(java.awt.event.WindowEvent evt) {//GEN-FIRST:event_formWindowClosing
        //Se pregunta si se desea cerrar el dialog

        if (this.hayCambio) {

            if (tomarDecision("No has guardado cambios. \nDeseas descartarlos?", "Descartar cambio")) {
                this.dispose();
            }
        }

        if (!this.hayCambio) {
            this.dispose();
        }


    }//GEN-LAST:event_formWindowClosing

